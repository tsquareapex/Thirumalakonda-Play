-- Thirumalakonda Plywoods – Supabase schema (apply when the Supabase project is connected)
create table parties (
  id text primary key,                      -- e.g. DMM00001 / VHYD00001 (generated by next_party_code)
  type text not null check (type in ('customer','vendor')),
  name text, phone text, email text, address text, city text,
  state text default 'Andhra Pradesh',
  tolerance_days int default 5,
  created_at timestamptz default now()
);
create table code_seq (prefix text primary key, last int not null default 0);
create or replace function next_party_code(p text) returns text language plpgsql as $$
declare n int; begin
  insert into code_seq(prefix,last) values (p,1) on conflict (prefix) do update set last = code_seq.last+1 returning last into n;
  return p || lpad(n::text,5,'0'); end $$;
create table bills (
  id text primary key, party_id text references parties(id), bill_date date default current_date,
  total numeric(12,2) not null, delivery text default 'Pending', created_at timestamptz default now()
);
create table bill_items (id bigserial primary key, bill_id text references bills(id) on delete cascade, code text, description text, qty numeric, price numeric);
create table payments (id bigserial primary key, bill_id text references bills(id) on delete cascade, paid_on date default current_date, amount numeric(12,2) not null);
create table returns (
  id text primary key, party_id text references parties(id), bill_id text references bills(id), item text, qty numeric, amount numeric(12,2),
  returned_on date default current_date, status text default 'Pending Pickup', driver_id bigint, created_at timestamptz default now()
);
create table employees (id bigserial primary key, name text not null, role text, phone text);
create table message_log (id bigserial primary key, party_id text, kind text, body text, channel text, sent_at timestamptz default now());

-- Row level security: only signed-in staff/owner may read/write
do $$ declare t text; begin
  foreach t in array array['parties','code_seq','bills','bill_items','payments','returns','employees','message_log'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy "staff all" on %I for all to authenticated using (true) with check (true)', t);
  end loop; end $$;
